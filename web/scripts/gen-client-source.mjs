// Embeds the canonical reference client (agents/client.py) into a TS module so
// the agent page can render it as a copy-able code block without reading the
// filesystem at runtime. Mirrors the schema.d.ts codegen: the output is
// committed, regenerated via `make openapi`, and drift-checked by `client:check`.
//
//   bun scripts/gen-client-source.mjs [path/to/client.py]
//
// The optional argument overrides the source path (used by the Docker build,
// where agents/client.py is copied to /tmp).
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const src = process.argv[2] ?? join(here, "..", "..", "agents", "client.py");
const out = join(here, "..", "src", "generated", "clientSource.ts");

const py = readFileSync(src, "utf8");
const banner =
  "// @generated by scripts/gen-client-source.mjs from agents/client.py — do not edit.\n";

mkdirSync(dirname(out), { recursive: true });
writeFileSync(
  out,
  `${banner}export const CLIENT_PY = ${JSON.stringify(py)};\n`,
);
